import { useMemo, useState } from 'react';
import { useAuth } from '../../context/AuthContext.jsx';
import { auditLabel } from '../../data/workflow.js';
import { roleInfo } from '../../data/roles.js';
import { useStore, platformStats, averageResolutionDays } from '../../services/store.js';
import {
  downloadCsv,
  stamp,
  submissionHeaders,
  submissionRow,
  toCsv,
} from '../../services/csv.js';
import Button from '../../components/Button.jsx';
import { PageHeader, Panel, formatDateTime } from '../../components/admin/ui.jsx';

/*
 * REPORTS & EXPORTS.
 *
 * This is what "Reports" ought to have meant. The old sidebar used that word
 * for submissions a student had tagged as a report, which is a filter on the
 * concerns page - so anybody coming here to pull this term's figures found a
 * list of complaints instead. The word is now used the way every other admin
 * panel uses it: take the records out of the system in a form you can hand to
 * somebody.
 *
 * Everything is generated in the browser from the records already loaded, so
 * there is no endpoint to build and nothing to keep in step.
 *
 * ON ANONYMITY
 * The submissions export offers a choice, and it defaults to leaving names
 * out. A spreadsheet has a way of being forwarded, and a student who ticked
 * "post anonymously" did not agree to appear in one. Including identities is
 * possible - administrators can already see them - but it has to be a
 * deliberate tick, not the default.
 */

function Exports() {
  const { user } = useAuth();
  const { db } = useStore(user);

  const [includeIdentities, setIncludeIdentities] = useState(false);
  const [lastExport, setLastExport] = useState('');

  const stats = useMemo(() => platformStats(db), [db]);
  const avgResolution = useMemo(() => averageResolutionDays(db), [db]);

  function note(what, count) {
    setLastExport(`${what} - ${count} ${count === 1 ? 'row' : 'rows'} downloaded.`);
  }

  function exportSubmissions() {
    const headers = submissionHeaders(includeIdentities);
    const rows = db.posts.map((post) => submissionRow(db, post, includeIdentities));

    downloadCsv(`campusvoicebox-submissions-${stamp()}.csv`, toCsv(headers, rows));
    note('Submissions', rows.length);
  }

  function exportUsers() {
    const headers = [
      'Account ID', 'Name', 'Email', 'Role', 'Status', 'Student ID',
      'Course', 'Year level', 'Section', 'Registered', 'Last login', 'Submissions',
    ];

    const rows = db.users.map((account) => [
      account.id,
      account.name,
      account.email,
      roleInfo(account.role).label,
      account.status,
      account.studentId ?? '',
      account.course ?? '',
      account.yearLevel ?? '',
      account.section ?? '',
      account.createdAt,
      account.lastLogin ?? '',
      db.posts.filter((post) => post.authorId === account.id).length,
    ]);

    downloadCsv(`campusvoicebox-users-${stamp()}.csv`, toCsv(headers, rows));
    note('Users', rows.length);
  }

  function exportActivity() {
    const headers = ['When', 'Administrator', 'Role', 'Action', 'Target type', 'Target ID', 'Details'];
    const rows = db.audit.map((entry) => [
      entry.createdAt,
      entry.adminName,
      entry.adminRole,
      auditLabel(entry.action),
      entry.targetType,
      entry.targetId,
      entry.details,
    ]);

    downloadCsv(`campusvoicebox-activity-log-${stamp()}.csv`, toCsv(headers, rows));
    note('Activity log', rows.length);
  }

  // A one-page summary, for pasting into a report rather than a spreadsheet.
  function exportSummary() {
    const headers = ['Measure', 'Value'];
    const rows = [
      ['Report generated', formatDateTime(new Date().toISOString())],
      ['Generated by', user?.name ?? ''],
      ['Total users', stats.totalUsers],
      ['Students', stats.totalStudents],
      ['Active users (30 days)', stats.activeUsers],
      ['Suspended accounts', stats.suspendedUsers],
      ['Total submissions', stats.totalPosts],
      ['Awaiting review', stats.pendingPosts],
      ['Published', stats.publishedPosts],
      ['Rejected', stats.rejectedPosts],
      ['Suggestions', stats.totalSuggestions],
      ['Concerns', stats.totalConcerns],
      ['Open concerns', stats.openConcerns],
      ['Resolved concerns', stats.resolvedConcerns],
      ['Total votes cast', stats.totalVotes],
      [
        // Every kind of submission, not concerns only - see averageResolutionDays.
        'Average resolution, any submission (days)',
        avgResolution === null ? 'Nothing resolved yet' : avgResolution.toFixed(1),
      ],
    ];

    downloadCsv(`campusvoicebox-summary-${stamp()}.csv`, toCsv(headers, rows));
    note('Summary', rows.length);
  }

  const exports = [
    {
      title: 'Submissions',
      description: 'Every post with its category, status, department, votes and resolution.',
      count: db.posts.length,
      action: exportSubmissions,
    },
    {
      title: 'Users',
      description: 'Every account with its role, course details and submission count.',
      count: db.users.length,
      action: exportUsers,
    },
    {
      title: 'Activity log',
      description: 'Every administrative action, for an audit trail you can hand over.',
      count: db.audit.length,
      action: exportActivity,
    },
    {
      title: 'Summary figures',
      description: 'The headline numbers on one page, for a report or a meeting.',
      count: 16,
      action: exportSummary,
    },
  ];

  return (
    <>
      <PageHeader
        title="Reports & Exports"
        description="Take the records out of the system as CSV, ready for a spreadsheet or a report."
      />

      {/*
        NO HEADLINE FIGURES HERE.
 
        Four cards used to sit above the downloads: Submissions, Users,
        Logged Actions and Avg. Resolution. Three of them printed exactly what
        the panel directly beneath already said - the Submissions card read 6
        and the Submissions download read "6 rows". The fourth belongs on
        Analytics, which shows it larger and in context.
 
        The row count on each download is the version worth keeping, because
        it tells you the size of the file you are about to take.
      */}
      {/*
        THE ANONYMITY SWITCH, above the downloads rather than tucked beside
        one of them - it changes what leaves the building, so it should be read
        before anything is clicked.
      */}
      <Panel className="mt-4" title="Before you export">
        <label
          htmlFor="include-identities"
          className="flex cursor-pointer items-start gap-3 rounded-lg border border-slate-200 bg-slate-50 p-3"
        >
          <input
            id="include-identities"
            type="checkbox"
            checked={includeIdentities}
            onChange={(event) => setIncludeIdentities(event.target.checked)}
            className="mt-0.5 h-4 w-4 shrink-0 rounded border-slate-300 text-navy-600 focus:ring-navy-600"
          />
          <span className="text-sm">
            <span className="font-semibold text-navy-900">
              Include author names in the submissions export
            </span>
            <span className="mt-0.5 block text-xs text-slate-500">
              Off by default. A student who posted anonymously agreed to their name being hidden on
              the board - a spreadsheet that gets forwarded is not covered by that. Turn this on
              only when the identities are genuinely needed, and handle the file accordingly.
            </span>
          </span>
        </label>

        {includeIdentities && (
          <p role="status" className="mt-3 rounded-lg bg-amber-50 px-3 py-2 text-sm text-amber-900">
            The submissions export will name every author, including those who posted anonymously.
          </p>
        )}
      </Panel>

      <div className="mt-4 grid gap-4 sm:grid-cols-2">
        {exports.map((item) => (
          <Panel key={item.title} title={item.title}>
            <p className="text-sm text-slate-600">{item.description}</p>
            <p className="mt-2 text-xs text-slate-400">
              {item.count} {item.count === 1 ? 'row' : 'rows'}
            </p>
            <div className="mt-3">
              <Button variant="primary" size="sm" onClick={item.action} disabled={item.count === 0}>
                Download CSV
              </Button>
            </div>
          </Panel>
        ))}
      </div>

      {lastExport && (
        <p role="status" className="mt-4 rounded-lg bg-emerald-50 px-3 py-2 text-sm text-emerald-800">
          {lastExport}
        </p>
      )}

      <p className="mt-6 text-center text-xs text-slate-400">
        Files are generated in your browser from the records already loaded - nothing is sent
        anywhere to produce them.
      </p>
    </>
  );
}

export default Exports;
